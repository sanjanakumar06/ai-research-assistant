import re
from app.services.vector_store import search_chunks
from app.services.llm import generate_answer


def answer_question(question: str, top_k: int = 3) -> dict:
    """
    Retrieve relevant document chunks and generate
    a context-grounded answer with source metadata.
    """

    if not question.strip():
        raise ValueError("Question cannot be empty")

    results = search_chunks(question, top_k=top_k)

    documents = results["documents"][0]
    metadatas = results["metadatas"][0]
    distances = results["distances"][0]

    if not documents:
        return {
            "question": question,
            "answer": "No relevant documents found.",
            "sources": []
        }

    context_parts = []
    sources = []

    for index, (text, metadata, distance) in enumerate(
        zip(documents, metadatas, distances),
        start=1
    ):
        context_parts.append(
            f"[{index}]\n"
            f"Document: {metadata['filename']}\n"
            f"Page: {metadata['page_number']}\n"
            f"Content: {text}"
        )

        sources.append({
            "source_id": index,
            "document_id": metadata["document_id"],
            "filename": metadata["filename"],
            "page_number": metadata["page_number"],
            "chunk_index": metadata["chunk_index"],
            "distance": float(distance),
            "excerpt": text
        })

    context = "\n\n".join(context_parts)

    answer = generate_answer(question, context)

    # Identify citations explicitly generated by the LLM
    citation_ids = {
        int(match)
        for match in re.findall(r"\[(\d+)\]", answer)
    }

    # Validate citation IDs against retrieved sources
    valid_ids = {source["source_id"] for source in sources}

    # Remove references to nonexistent sources
    answer = re.sub(
        r"\[(\d+)\]",
        lambda match: (
            match.group(0)
            if int(match.group(1)) in valid_ids
            else ""
        ),
        answer
    ).strip()

    # Identify which retrieved sources were explicitly cited
    for source in sources:
        source["cited"] = source["source_id"] in citation_ids

    return {
        "question": question,
        "answer": answer,
        "sources": sources
    }